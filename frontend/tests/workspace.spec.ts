import { expect, test } from '@playwright/test'

// These tests use the real API and database, not mocked responses.
const username = process.env.E2E_USERNAME || 'admin'
const password = process.env.E2E_PASSWORD || 'Admin@123456'

test('login, real content, filters, paging, reload, logout and route protection', async ({ page }) => {
  await page.goto('/content')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByRole('button', { name: '登录工作台' }).click()
  await expect(page.getByText('请输入用户名', { exact: true })).toBeVisible()
  await page.getByLabel('用户名', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: '登录工作台' }).click()
  await expect(page.getByRole('alert').filter({ hasText: '用户名或密码错误' })).toBeVisible()
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录工作台' }).click()
  await expect(page).toHaveURL(/\/content$/)
  await expect(page.getByRole('button', { name: '欢迎使用启程工作台', exact: true })).toBeVisible()
  await expect(page.getByText('共 8 篇内容')).toBeVisible()
  await page.getByRole('button', { name: '草稿', exact: true }).click()
  await expect(page.getByText('共 3 篇内容')).toBeVisible()
  await expect(page.getByRole('button', { name: '新项目启动清单', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '全部内容', exact: true }).click()
  const search = page.getByRole('textbox', { name: '搜索内容标题' })
  await search.fill('前后端')
  await expect(page.getByText('共 1 篇内容')).toBeVisible()
  await page.getByRole('button', { name: '前后端协作指南', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('了解独立部署、接口约定与本地代理')
  await page.keyboard.press('Escape')
  await search.fill('不存在的内容标题')
  await expect(page.getByText('没有找到相关内容')).toBeVisible()
  await page.getByRole('button', { name: '清除筛选', exact: true }).click()
  await expect(page.getByText('共 8 篇内容')).toBeVisible()
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.getByRole('button', { name: '本周工作回顾', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.reload()
  await expect(page).toHaveURL(/\/content$/)
  await expect(page.getByRole('button', { name: '欢迎使用启程工作台', exact: true })).toBeVisible()
  const token = await page.evaluate(() => sessionStorage.getItem('qicheng.access-token'))
  await page.getByRole('button', { name: '账户菜单' }).click()
  await page.getByRole('menuitem', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  const response = await page.request.get('/api/auth/me', { headers: { Authorization: `Bearer ${token}` } })
  expect(response.status()).toBe(401)
  await page.goto('/content')
  await expect(page).toHaveURL(/\/login$/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('expired token returns to login', async ({ page }) => {
  await page.goto('/login')
  await page.evaluate(() => sessionStorage.setItem('qicheng.access-token', 'expired-token'))
  await page.goto('/content')
  await expect(page).toHaveURL(/\/login/)
  expect(await page.evaluate(() => sessionStorage.getItem('qicheng.access-token'))).toBeNull()
})
